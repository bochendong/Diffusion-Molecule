#!/usr/bin/env bash
# Generate one maximum candidate pool and derive all requested prefix budgets offline.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="$(cd "$SCRIPT_DIR/../../.." && pwd)"
cd "$REPO_DIR"

TASK="${SUCC_UNIFIED_JOINT_EVAL_TASK:?Set SUCC_UNIFIED_JOINT_EVAL_TASK}"
CHECKPOINT="${SUCC_UNIFIED_CHECKPOINT:?Set SUCC_UNIFIED_CHECKPOINT}"
EVAL_CSV="${SUCC_UNIFIED_EVAL_CSV:?Set SUCC_UNIFIED_EVAL_CSV}"
EVAL_FEATURES_DIR="${SUCC_UNIFIED_EVAL_FEATURES_DIR:?Set SUCC_UNIFIED_EVAL_FEATURES_DIR}"
OUTPUT_ROOT="${SUCC_UNIFIED_BENCHMARK_OUTPUT_DIR:?Set SUCC_UNIFIED_BENCHMARK_OUTPUT_DIR}"
BUDGETS="${SUCC_UNIFIED_CANDIDATE_BUDGETS:-1,20,128,256}"
MAX_CANDIDATES="${SUCC_UNIFIED_MAX_CANDIDATES:-256}"
EVAL_SEED="${SUCC_UNIFIED_SEED:-101}"
TABLE1_REFERENCE="${SUCC_UNIFIED_MOLEDIT_REFERENCE_CSV:-}"

case "$TASK" in
2p7p)
  BENCHMARK_TASKS=denovo_2p7p
  INPUT_MODALITY=text_property
  ;;
ood)
  BENCHMARK_TASKS=denovo_ood
  INPUT_MODALITY=text_property
  ;;
table1)
  BENCHMARK_TASKS=moledit_table1
  INPUT_MODALITY=source_structure_text
  if [[ -z "$TABLE1_REFERENCE" ]]; then
    echo "ERROR: SUCC_UNIFIED_MOLEDIT_REFERENCE_CSV is required for table1" >&2
    exit 2
  fi
  ;;
*)
  echo "ERROR: unsupported task=$TASK" >&2
  exit 2
  ;;
esac

SUCC_UNIFIED_BENCHMARK_RUN_SAMPLE=1 \
SUCC_UNIFIED_CHECKPOINT="$CHECKPOINT" \
SUCC_UNIFIED_EVAL_CSV="$EVAL_CSV" \
SUCC_UNIFIED_EVAL_FEATURES_DIR="$EVAL_FEATURES_DIR" \
SUCC_UNIFIED_BENCHMARK_OUTPUT_DIR="$OUTPUT_ROOT" \
SUCC_UNIFIED_SAMPLE_OUTPUT_DIR="$OUTPUT_ROOT/candidate_pool" \
SUCC_UNIFIED_BENCHMARK_TASKS="$BENCHMARK_TASKS" \
SUCC_UNIFIED_CONDITION_LAYOUT="${SUCC_UNIFIED_CONDITION_LAYOUT:-direct_compat}" \
SUCC_UNIFIED_CONDITION_FEATURE_VARIANT="${SUCC_UNIFIED_CONDITION_FEATURE_VARIANT:-full}" \
SUCC_UNIFIED_INPUT_MODALITY="$INPUT_MODALITY" \
SUCC_UNIFIED_METHOD_NAME="${SUCC_UNIFIED_METHOD_NAME:-unified_joint_v2_${TASK}}" \
SUCC_UNIFIED_DECODING_MODE=sample \
SUCC_UNIFIED_NUM_SAMPLES="$MAX_CANDIDATES" \
SUCC_UNIFIED_MAX_CANDIDATES="$MAX_CANDIDATES" \
SUCC_UNIFIED_TOP_K_CANDIDATES="$MAX_CANDIDATES" \
SUCC_UNIFIED_CANDIDATE_BUDGETS="$BUDGETS" \
SUCC_UNIFIED_SELECTION_MODES="${SUCC_UNIFIED_SELECTION_MODES:-raw,finalizer}" \
SUCC_UNIFIED_INCLUDE_SOURCE_COPY_CANDIDATE="${SUCC_UNIFIED_INCLUDE_SOURCE_COPY_CANDIDATE:-0}" \
SUCC_UNIFIED_TEMPERATURE="${SUCC_UNIFIED_TEMPERATURE:-0.85}" \
SUCC_UNIFIED_TOP_K="${SUCC_UNIFIED_TOP_K:-40}" \
SUCC_UNIFIED_TOP_P="${SUCC_UNIFIED_TOP_P:-0.95}" \
SUCC_UNIFIED_PARALLEL_SAMPLES="${SUCC_UNIFIED_PARALLEL_SAMPLES:-8}" \
SUCC_UNIFIED_SEED="$EVAL_SEED" \
SUCC_UNIFIED_MOLEDIT_REFERENCE_CSV="$TABLE1_REFERENCE" \
SUCC_UNIFIED_MOLEDIT_REQUIRE_TABLE1_COVERAGE="${SUCC_UNIFIED_MOLEDIT_REQUIRE_TABLE1_COVERAGE:-1}" \
bash "$SCRIPT_DIR/run_unified_smiles_generator_benchmark_suite.sh"

metadata_args=(
  "$SCRIPT_DIR/write_unified_joint_run_metadata.py"
  --task "$TASK"
  --stage "${SUCC_UNIFIED_JOINT_STAGE:-unknown}"
  --train-seed "${SUCC_UNIFIED_TRAIN_SEED:-unknown}"
  --eval-seed "$EVAL_SEED"
  --checkpoint "$CHECKPOINT"
  --eval-csv "$EVAL_CSV"
  --candidate-csv "$OUTPUT_ROOT/candidate_pool/unified_smiles_candidate_predictions.csv"
  --output-json "$OUTPUT_ROOT/joint_v2_run_metadata.json"
  --candidate-budgets "$BUDGETS"
  --selection-modes "${SUCC_UNIFIED_SELECTION_MODES:-raw,finalizer}"
  --max-candidates "$MAX_CANDIDATES"
  --input-modality "$INPUT_MODALITY"
)
if [[ "${SUCC_UNIFIED_INCLUDE_SOURCE_COPY_CANDIDATE:-0}" == "1" ]]; then
  metadata_args+=(--include-source-copy-candidate)
fi
"${SUCC_PYTHON_BIN:-python3}" "${metadata_args[@]}"

echo "Unified Joint v2 single-pool eval complete:"
echo "  task=$TASK"
echo "  checkpoint=$CHECKPOINT"
echo "  eval_seed=$EVAL_SEED"
echo "  max_candidates=$MAX_CANDIDATES"
echo "  budgets=$BUDGETS"
echo "  output_root=$OUTPUT_ROOT"
