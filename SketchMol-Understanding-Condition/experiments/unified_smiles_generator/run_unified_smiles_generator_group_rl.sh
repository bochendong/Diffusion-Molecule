#!/usr/bin/env bash
# Task-aware group-relative RL for the standalone unified SMILES generator.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="$(cd "$SCRIPT_DIR/../../.." && pwd)"
cd "$REPO_DIR"

PYTHON_BIN="${SUCC_PYTHON_BIN:-${PYTHON_BIN:-python3}}"
TRAIN_CSV="${SUCC_UNIFIED_RL_TRAIN_CSV:-${SUCC_UNIFIED_TRAIN_CSV:-}}"
EVAL_CSV="${SUCC_UNIFIED_RL_EVAL_CSV:-${SUCC_UNIFIED_EVAL_CSV:-}}"
OUTPUT_DIR="${SUCC_UNIFIED_RL_OUTPUT_DIR:-SketchMol-Understanding-Condition/outputs/unified_smiles_generator_group_rl_v1}"
RESUME_CHECKPOINT="${SUCC_UNIFIED_RL_RESUME_CHECKPOINT:-${SUCC_UNIFIED_CHECKPOINT:-SketchMol-Understanding-Condition/outputs/unified_smiles_generator_v1/unified_smiles_generator.pt}}"
TRAIN_FEATURES_DIR="${SUCC_UNIFIED_RL_TRAIN_FEATURES_DIR:-${SUCC_UNIFIED_TRAIN_FEATURES_DIR:-}}"
EVAL_FEATURES_DIR="${SUCC_UNIFIED_RL_EVAL_FEATURES_DIR:-${SUCC_UNIFIED_EVAL_FEATURES_DIR:-$TRAIN_FEATURES_DIR}}"
CONDITION_FEATURE_ARRAY="${SUCC_UNIFIED_CONDITION_FEATURE_ARRAY:-query_tokens}"
CONDITION_FEATURE_VARIANT="${SUCC_UNIFIED_CONDITION_FEATURE_VARIANT:-full}"
INPUT_MODALITY="${SUCC_UNIFIED_INPUT_MODALITY:-}"
CONDITION_DIM="${SUCC_UNIFIED_CONDITION_DIM:-256}"
MAX_SMILES_LENGTH="${SUCC_UNIFIED_MAX_SMILES_LENGTH:-160}"
MAX_SOURCE_TOKENS="${SUCC_UNIFIED_MAX_SOURCE_TOKENS:-96}"

EPOCHS="${SUCC_UNIFIED_RL_EPOCHS:-1}"
BATCH_SIZE="${SUCC_UNIFIED_RL_BATCH_SIZE:-8}"
EVAL_BATCH_SIZE="${SUCC_UNIFIED_RL_EVAL_BATCH_SIZE:-32}"
LR="${SUCC_UNIFIED_RL_LR:-1e-6}"
WEIGHT_DECAY="${SUCC_UNIFIED_RL_WEIGHT_DECAY:-1e-4}"
GRAD_CLIP="${SUCC_UNIFIED_RL_GRAD_CLIP:-1.0}"
ROLLOUTS_PER_PROMPT="${SUCC_UNIFIED_RL_ROLLOUTS_PER_PROMPT:-16}"
SFT_WEIGHT="${SUCC_UNIFIED_RL_SFT_WEIGHT:-0.25}"
ADVANTAGE_MODE="${SUCC_UNIFIED_RL_ADVANTAGE_MODE:-group_zscore}"
ADVANTAGE_CLIP="${SUCC_UNIFIED_RL_ADVANTAGE_CLIP:-3.0}"
SEQUENCE_LOGPROB_REDUCTION="${SUCC_UNIFIED_RL_SEQUENCE_LOGPROB_REDUCTION:-mean}"
REFERENCE_KL_WEIGHT="${SUCC_UNIFIED_RL_REFERENCE_KL_WEIGHT:-0.05}"
REWARD_MODE="${SUCC_UNIFIED_RL_REWARD_MODE:-auto}"
REWARD_VALID_WEIGHT="${SUCC_UNIFIED_RL_REWARD_VALID_WEIGHT:-0.25}"
REWARD_STRICT_WEIGHT="${SUCC_UNIFIED_RL_REWARD_STRICT_WEIGHT:-2.0}"
REWARD_DISTANCE_WEIGHT="${SUCC_UNIFIED_RL_REWARD_DISTANCE_WEIGHT:-0.05}"
REWARD_DISTANCE_CLIP="${SUCC_UNIFIED_RL_REWARD_DISTANCE_CLIP:-10.0}"
REWARD_SOURCE_SIMILARITY_WEIGHT="${SUCC_UNIFIED_RL_REWARD_SOURCE_SIMILARITY_WEIGHT:-0.5}"
REWARD_SOURCE_SIMILARITY_THRESHOLD="${SUCC_UNIFIED_RL_REWARD_SOURCE_SIMILARITY_THRESHOLD:-0.4}"
REWARD_SOURCE_COPY_PENALTY="${SUCC_UNIFIED_RL_REWARD_SOURCE_COPY_PENALTY:-0.5}"

DECODING_MODE="${SUCC_UNIFIED_DECODING_MODE:-sample}"
NUM_SAMPLES="${SUCC_UNIFIED_NUM_SAMPLES:-20}"
BEAM_SIZE="${SUCC_UNIFIED_BEAM_SIZE:-20}"
BEAM_EXPAND_SIZE="${SUCC_UNIFIED_BEAM_EXPAND_SIZE:-64}"
BEAM_LENGTH_PENALTY="${SUCC_UNIFIED_BEAM_LENGTH_PENALTY:-0.8}"
TOP_K_CANDIDATES="${SUCC_UNIFIED_TOP_K_CANDIDATES:-40}"
MAX_NEW_TOKENS="${SUCC_UNIFIED_RL_MAX_NEW_TOKENS:-${SUCC_UNIFIED_MAX_NEW_TOKENS:-160}}"
TEMPERATURE="${SUCC_UNIFIED_RL_TEMPERATURE:-${SUCC_UNIFIED_TEMPERATURE:-0.85}}"
TOP_K="${SUCC_UNIFIED_RL_TOP_K:-${SUCC_UNIFIED_TOP_K:-40}}"
TOP_P="${SUCC_UNIFIED_RL_TOP_P:-${SUCC_UNIFIED_TOP_P:-0.95}}"
PARALLEL_SAMPLES="${SUCC_UNIFIED_RL_PARALLEL_SAMPLES:-${SUCC_UNIFIED_PARALLEL_SAMPLES:-4}}"
MAX_PARALLEL_SEQUENCES="${SUCC_UNIFIED_RL_MAX_PARALLEL_SEQUENCES:-${SUCC_UNIFIED_MAX_PARALLEL_SEQUENCES:-512}}"
REPETITION_PENALTY="${SUCC_UNIFIED_RL_REPETITION_PENALTY:-${SUCC_UNIFIED_REPETITION_PENALTY:-1.15}}"
NO_REPEAT_NGRAM_SIZE="${SUCC_UNIFIED_RL_NO_REPEAT_NGRAM_SIZE:-${SUCC_UNIFIED_NO_REPEAT_NGRAM_SIZE:-6}}"
MIN_NEW_TOKENS="${SUCC_UNIFIED_RL_MIN_NEW_TOKENS:-${SUCC_UNIFIED_MIN_NEW_TOKENS:-6}}"
SEED="${SUCC_UNIFIED_RL_SEED:-${SUCC_UNIFIED_SEED:-7}}"
DEVICE="${SUCC_DEVICE:-${SUCC_UNIFIED_DEVICE:-auto}}"

if [[ -z "$TRAIN_CSV" ]]; then
  echo "ERROR: set SUCC_UNIFIED_RL_TRAIN_CSV or SUCC_UNIFIED_TRAIN_CSV" >&2
  exit 2
fi

args=(
  "$SCRIPT_DIR/unified_smiles_generator.py"
  group-rl
  --train-csv "$TRAIN_CSV"
  --output-dir "$OUTPUT_DIR"
  --resume-checkpoint "$RESUME_CHECKPOINT"
  --condition-feature-array "$CONDITION_FEATURE_ARRAY"
  --condition-feature-variant "$CONDITION_FEATURE_VARIANT"
  --condition-dim "$CONDITION_DIM"
  --max-smiles-length "$MAX_SMILES_LENGTH"
  --max-source-tokens "$MAX_SOURCE_TOKENS"
  --epochs "$EPOCHS"
  --batch-size "$BATCH_SIZE"
  --eval-batch-size "$EVAL_BATCH_SIZE"
  --lr "$LR"
  --weight-decay "$WEIGHT_DECAY"
  --grad-clip "$GRAD_CLIP"
  --rollouts-per-prompt "$ROLLOUTS_PER_PROMPT"
  --sft-weight "$SFT_WEIGHT"
  --advantage-mode "$ADVANTAGE_MODE"
  --advantage-clip "$ADVANTAGE_CLIP"
  --sequence-logprob-reduction "$SEQUENCE_LOGPROB_REDUCTION"
  --reference-kl-weight "$REFERENCE_KL_WEIGHT"
  --reward-mode "$REWARD_MODE"
  --reward-valid-weight "$REWARD_VALID_WEIGHT"
  --reward-strict-weight "$REWARD_STRICT_WEIGHT"
  --reward-distance-weight "$REWARD_DISTANCE_WEIGHT"
  --reward-distance-clip "$REWARD_DISTANCE_CLIP"
  --reward-source-similarity-weight "$REWARD_SOURCE_SIMILARITY_WEIGHT"
  --reward-source-similarity-threshold "$REWARD_SOURCE_SIMILARITY_THRESHOLD"
  --reward-source-copy-penalty "$REWARD_SOURCE_COPY_PENALTY"
  --decoding-mode "$DECODING_MODE"
  --num-samples "$NUM_SAMPLES"
  --beam-size "$BEAM_SIZE"
  --beam-expand-size "$BEAM_EXPAND_SIZE"
  --beam-length-penalty "$BEAM_LENGTH_PENALTY"
  --top-k-candidates "$TOP_K_CANDIDATES"
  --max-new-tokens "$MAX_NEW_TOKENS"
  --temperature "$TEMPERATURE"
  --top-k "$TOP_K"
  --top-p "$TOP_P"
  --parallel-samples "$PARALLEL_SAMPLES"
  --max-parallel-sequences "$MAX_PARALLEL_SEQUENCES"
  --repetition-penalty "$REPETITION_PENALTY"
  --no-repeat-ngram-size "$NO_REPEAT_NGRAM_SIZE"
  --min-new-tokens "$MIN_NEW_TOKENS"
  --seed "$SEED"
  --device "$DEVICE"
)

if [[ -n "$INPUT_MODALITY" ]]; then
  args+=(--input-modality "$INPUT_MODALITY")
fi
if [[ -n "$EVAL_CSV" ]]; then
  args+=(--eval-csv "$EVAL_CSV")
fi
if [[ -n "$TRAIN_FEATURES_DIR" ]]; then
  args+=(--condition-features-dir "$TRAIN_FEATURES_DIR")
fi
if [[ -n "$EVAL_FEATURES_DIR" ]]; then
  args+=(--eval-condition-features-dir "$EVAL_FEATURES_DIR")
fi
if [[ -n "${SUCC_UNIFIED_RL_LIMIT:-}" ]]; then
  args+=(--limit "$SUCC_UNIFIED_RL_LIMIT")
fi
if [[ -n "${SUCC_UNIFIED_RL_EVAL_LIMIT:-}" ]]; then
  args+=(--eval-limit "$SUCC_UNIFIED_RL_EVAL_LIMIT")
fi

echo "Unified SMILES generator group RL"
echo "  train_csv=$TRAIN_CSV"
echo "  eval_csv=${EVAL_CSV:-none}"
echo "  output_dir=$OUTPUT_DIR"
echo "  resume_checkpoint=$RESUME_CHECKPOINT"
echo "  condition_feature_variant=$CONDITION_FEATURE_VARIANT"
echo "  input_modality=${INPUT_MODALITY:-auto}"
echo "  reward_mode=$REWARD_MODE"
echo "  rollouts_per_prompt=$ROLLOUTS_PER_PROMPT"
echo "  decoding_mode=$DECODING_MODE"

"$PYTHON_BIN" "${args[@]}"
